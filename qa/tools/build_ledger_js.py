#!/usr/bin/env python3
"""Generate site/data/ledger.js from qa/ledger.json and qa/series.json.
The output holds only official facts, official series and their source links. No household data."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
ledger = json.loads((root / "qa/ledger.json").read_text())
series = json.loads((root / "qa/series.json").read_text())
for e in ledger:
    assert e["url"].startswith("https://"), e["id"]
out = ("/* Generated by qa/tools/build_ledger_js.py from qa/ledger.json and qa/series.json. Do not edit by hand.\n"
       "   Official facts re-opened on 2026-11-11 by session f16e6e34. Contains no household data. */\n"
       "window.LEDGER = " + json.dumps(ledger, ensure_ascii=False, indent=1) + ";\n"
       "window.SERIES = " + json.dumps(series, ensure_ascii=False) + ";\n")
(root / "site/data/ledger.js").write_text(out, encoding="utf-8")
print(f"site/data/ledger.js: {len(ledger)} ledger entries, {len(series)-1} series")
