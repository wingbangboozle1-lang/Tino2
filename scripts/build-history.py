#!/usr/bin/env python3
"""Generate site/data/history.js from research/data/fred_annual_2026-11-11.csv.
The CSV holds annual values downloaded from FRED (Federal Reserve Bank of St. Louis) on 2026-11-11.
Series: CPIAUCNS (BLS CPI-U, annual average), ATNHPIUS41940Q (FHFA all-transactions HPI, San Jose MSA, Q4),
ATNHPIUS41884Q (FHFA HPI, San Francisco-San Mateo-Redwood City MD, Q4), CASTHPI (FHFA HPI, California, Q4),
GS10 (10-yr Treasury, annual average), MORTGAGE30US (Freddie Mac 30-yr, annual average),
SPASTT01USM661N (OECD US share-price index, year-end)."""
import csv, json, os
root = os.path.join(os.path.dirname(__file__), "..")
rows = list(csv.DictReader(open(os.path.join(root, "research/data/fred_annual_2026-11-11.csv"))))
cols = ["cpi", "sj", "sf", "ca", "gs10", "mort", "eq"]
src = ["cpi_avg_cpiaucns", "sj_hpi_atnhpius41940q", "sf_hpi_atnhpius41884q", "ca_hpi_casthpi", "gs10_avg", "mortgage30_avg", "oecd_us_share_price_spastt01usm661n"]
data = []
for r in rows:
    data.append([int(r["year"])] + [float(r[s]) if r[s] else None for s in src])
js = "/* Generated by scripts/build-history.py from research/data/fred_annual_2026-11-11.csv. Index levels, not dollar amounts. */\nwindow.HISTORY = " + json.dumps({"columns": ["year"] + cols, "rows": data}, separators=(",", ":")) + ";\n"
open(os.path.join(root, "site/data/history.js"), "w").write(js)
print("rows", len(data))
